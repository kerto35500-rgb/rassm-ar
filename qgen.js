/* ── مولّد عشوائي حتميّ ── */
function rng(seed) {
  let s = seed >>> 0;
  return () => { s = (s + 0x6D2B79F5) >>> 0; let t = s; t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61); return ((t ^ (t >>> 14)) >>> 0) / 4294967296; };
}
const R = rng(20260830);
function pick3(pool, notOf) {
  const out = [], seen = new Set(notOf.map(String));
  const arr = pool.slice();
  while (out.length < 3 && arr.length) {
    const i = Math.floor(R() * arr.length), v = arr.splice(i, 1)[0];
    if (v && !seen.has(String(v))) { seen.add(String(v)); out.push(v); }
  }
  while (out.length < 3) out.push("—" + out.length);
  return out;
}

