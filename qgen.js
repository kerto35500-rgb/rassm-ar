function geography() {
  const out = [];
  const capsBy = {}, namesBy = {};
  COUNTRIES.forEach(([n, c, k]) => {
    (capsBy[k] = capsBy[k] || []).push(c);
    (namesBy[k] = namesBy[k] || []).push(n);
  });
  const allCur = [...new Set(COUNTRIES.map(r => r[3]))];
  COUNTRIES.forEach(([n, cap, kon, cur], i) => {
    const d = i < 40 ? 1 : 2;
    out.push(["ما عاصمة " + n + "؟", cap, ...pick3(capsBy[kon], [cap]), d]);
    out.push(["ما الدولة التي عاصمتها " + cap + "؟", n, ...pick3(namesBy[kon], [n]), d]);
    out.push(["في أي قارة تقع " + n + "؟", kon, ...pick3(CONTINENTS, [kon]), 1]);
    out.push(["ما العملة الرسمية في " + n + "؟", cur, ...pick3(allCur, [cur]), d === 1 ? 2 : 3]);
  });
  return out;
}

