/* ═════════ ٣· الألغاز الحسابية والمتتاليات (مولّدة) ═════════ */
const AR = n => String(n);
function puzzles() {
  const out = [];
  // ضرب
  for (let a = 3; a <= 12; a++) for (let b = 3; b <= 12; b++) {
    if ((a * 13 + b) % 3) continue;
    const v = a * b;
    out.push(["ما ناتج " + a + " × " + b + "؟", AR(v),
      AR(v + a), AR(v - b), AR(v + b + 1), v > 60 ? 2 : 1]);
  }
  // نسب مئوية
  [[10,80],[25,80],[50,240],[20,150],[75,200],[5,300],[30,90],[40,250],[60,150],[15,200],
   [25,160],[10,45],[20,85],[50,130],[35,200]].forEach(([p, n]) => {
    const v = p * n / 100;
    out.push(["كم يساوي " + p + "٪ من " + n + "؟", AR(v), AR(v + 5), AR(v * 2), AR(v - 5), 2]);
  });
  // متتاليات حسابية
  for (let s = 2; s <= 9; s++) for (let st = 2; st <= 9; st++) {
    if ((s + st) % 4) continue;
    const seq = [s, s + st, s + 2 * st, s + 3 * st], nx = s + 4 * st;
    out.push(["ما العدد التالي في المتتالية: " + seq.join("، ") + "؟", AR(nx),
      AR(nx + st), AR(nx - 1), AR(nx + 1), 1]);
  }
  // متتاليات هندسية
  [2,3,4,5].forEach(r => [1,2,3].forEach(s => {
    const seq = [s, s*r, s*r*r, s*r*r*r], nx = s*r*r*r*r;
    out.push(["ما العدد التالي في المتتالية: " + seq.join("، ") + "؟", AR(nx),
      AR(nx + r), AR(nx * 2), AR(nx - r), 2]);
  }));
  // مربّعات ومكعّبات
  for (let n = 4; n <= 20; n++) {
    out.push(["ما جذر العدد " + (n * n) + " التربيعي؟", AR(n), AR(n + 1), AR(n - 1), AR(n + 2), n > 12 ? 2 : 1]);
  }
  for (let n = 2; n <= 9; n++) {
    out.push(["ما ناتج " + n + " تكعيب (" + n + "³)؟", AR(n ** 3), AR(n ** 3 + n), AR(n * n * 2), AR(n ** 3 - n), 2]);
  }
  // أعمار
  [[2,7],[3,5],[2,12],[4,6],[3,9],[2,18],[5,4],[3,14]].forEach(([k, y]) => {
    out.push(["إذا كان عمر سالم " + y + " سنة وعمر أحمد يساوي " + (k === 2 ? "ضعف" : k + " أضعاف") +
      " عمره، فكم عمر أحمد؟", AR(k * y), AR(k * y + y), AR(k * y - y), AR(k * y + 2), 2]);
  });
  // قسمة
  for (let b = 3; b <= 12; b++) for (let q = 4; q <= 12; q++) {
    if ((b * q) % 5) continue;
    out.push(["ما ناتج قسمة " + (b * q) + " على " + b + "؟", AR(q), AR(q + 1), AR(q - 1), AR(q + 2), 1]);
  }
  // جمع متتابع
  [10,20,30,50,100].forEach(n => {
    const v = n * (n + 1) / 2;
    out.push(["ما مجموع الأعداد من 1 إلى " + n + "؟", AR(v), AR(v + n), AR(v - n), AR(v * 2), 3]);
  });
  return out;
}

/* ═════════ التجميع ═════════ */
// ضمان أربعة خيارات مختلفة: لو تكرّر خيار عدّلناه (رقمياً أو بعلامة)
function sanitize(rows) {
  const seenQ = new Set(), out = [];
  rows.forEach(r => {
    if (!r || r.length !== 6 || !r[0] || seenQ.has(r[0])) return;
    seenQ.add(r[0]);
    const opts = [r[1]];
    for (let i = 2; i <= 4; i++) {
      let v = r[i], guard = 0;
      while (opts.includes(v) && guard++ < 40) {
        const n = Number(v);
        v = isNaN(n) ? v + " " : String(n + guard);
      }
      opts.push(v);
    }
    if (new Set(opts).size !== 4) return;
    out.push([r[0], opts[0], opts[1], opts[2], opts[3], r[5]]);
  });
  return out;
}
function generate() {
  return {
    "جغرافيا": sanitize(geography()),
    "علوم": sanitize(chemistry()),
    "ألغاز": sanitize(puzzles())
  };
}

