// ضمان أربعة خيارات مختلفة: لو تكرّر خيار عدّلناه (رقمياً أو بعلامة)
function sanitize(rows) {
  const seenQ = new Set(), out = [];
  rows.forEach(r => {
    if (!r || r.length !== 6 || !r[0] || seenQ.has(r[0])) return;
    seenQ.add(r[0]);
    const opts = [r[1]];
    for (let i = 2; i <= 4; i++) {
      let v = r[i], guard = 0;
      while (opts.includes(v) && guard++ < 40) {
        const n = Number(v);
        v = isNaN(n) ? v + " " : String(n + guard);
      }
      opts.push(v);
    }
    if (new Set(opts).size !== 4) return;
    out.push([r[0], opts[0], opts[1], opts[2], opts[3], r[5]]);
  });
  return out;
}
