// اختبار مرشِّح الدردشة.
//
// المرشِّح يُقاس بشيئين: ماذا يمنع، وماذا **لا** يمنع. مرشِّحٌ يمنع كلّ شيء
// سهلٌ وعديمُ الفائدة — فنصفُ الاختبارات هنا جملٌ بريئةٌ يجب أن تمرّ.

const F = require("./chatfilter");

let P = 0, C = 0;
const ok = (c, m, x) => { c ? P++ : C++; console.log((c ? "  ✅ " : "  ❌ ") + m + (c ? "" : " → " + JSON.stringify(x))); };
const pass = (t, m) => { const r = F.check(t); ok(r.ok, m + ` — «${t}»`, r); };
const block = (t, m) => { const r = F.check(t); ok(!r.ok, m + ` — «${t}»`, r); };

console.log("\n═══ مرشِّح الدردشة ═══\n");

console.log("① ما يجب أن يمرّ");
{
  pass("يا سلام لعبٌ نظيف", "جملةٌ عاديّة");
  pass("صنّها يا شريك", "لهجةٌ في محلّها");
  pass("عندي مية وخمسين", "أرقامٌ قصيرةٌ مكتوبة");
  pass("خذ 3 أكلات وخلّها", "رقمٌ صغير");
  pass("👏👏 حلو", "إيموجي مع كلمة");
  pass("الله يعطيك العافية", "دعاء");
  pass("حمار الوحش في الصحراء", "كلمةٌ قد تُساء وهي بريئة");
  pass("كلب الصيد سريع", "وأخرى مثلها");
  pass("انتظر شوي أفكّر", "طلبُ مهلة");
  pass("ok", "كلمةٌ إنجليزيّةٌ قصيرة");
  pass("good game 👍", "عبارةٌ إنجليزيّةٌ مهذّبة");
  const r = F.check("   مرحبا    بكم   ");
  ok(r.ok && r.text === "مرحبا بكم", "والفراغ الزائد يُطوى", r);
}

console.log("② الروابط والحسابات");
{
  block("شوف https://example.com", "رابطٌ صريح");
  block("ادخل www.site.net", "ورابطٌ بلا بروتوكول");
  block("موقعي cool-site.xyz", "ونطاقٌ عاريًا");
  block("واتس 0500000000", "رقمُ جوّال");
  block("كلّمني على واتساب", "إحالةٌ لمنصّةٍ أخرى");
  block("سناب: abc123", "وأخرى");
  block("حسابي @mohammed_x", "ومعرّفٌ بعلامة");
  block("رقمي 966501234567", "رقمٌ دوليّ طويل");
}

console.log("③ الألفاظ");
{
  block("يا كلب انت شرموط", "لفظٌ صريح");
  block("ش ر م و ط", "ومموّهٌ بالفراغات");
  block("شـرمـوط", "ومموّهٌ بالتطويل");
  block("شرمووووط", "ومموّهٌ بالتكرار");
  block("fuck you", "وبالإنجليزيّة");
  block("F U C K", "ومموّهةً كذلك");
  block("شرموطة", "ومع تاء التأنيث");
}

console.log("④ الإغراق");
{
  block("", "رسالةٌ فارغة");
  block("     ", "أو فراغٌ فقط");
  block("اااااااااااااا", "حرفٌ مكرَّرٌ يملأ السطر");
  block("!!!!!!!!!!!!!!!!", "وعلاماتٌ بلا معنى");
  const long = "أ".repeat(400);
  const r = F.check("مرحبا " + long.replace(/أ/g, "ب ").slice(0, 400));
  ok(!r.ok || r.text.length <= F.MAX_LEN, "والطويلُ يُقصّ إلى الحدّ", r.text && r.text.length);
}

console.log("⑤ التطبيع");
{
  ok(F.normalize("أإآا") === "ا", "أشكال الألف تُوحَّد ثمّ يُقلَّص تكرارها", F.normalize("أإآا"));
  ok(F.normalize("ىي") === "ي", "والألف المقصورة", F.normalize("ىي"));
  ok(F.normalize("ةه") === "ه", "والتاء المربوطة", F.normalize("ةه"));
  ok(F.normalize("سـ__لام") === "سلام", "والتطويل والفواصل تسقط", F.normalize("سـ__لام"));
  ok(F.normalize("سلاااام") === "سلام", "والتكرار يُقلَّص إلى حرف", F.normalize("سلاااام"));
  ok(F.normalize("س ل ا م") === "سلام", "والفراغ يسقط", F.normalize("س ل ا م"));
}

console.log("⑥ المدخلات الشاذّة");
{
  ok(!F.check(null).ok, "null يُردّ");
  ok(!F.check(undefined).ok, "و undefined");
  ok(!F.check({}).ok || typeof F.check({}).text === "string", "وكائنٌ لا يكسر شيئًا");
  ok(!F.check(12345).ok || F.check(12345).ok, "ورقمٌ لا يرمي استثناءً");
  ok(typeof F.check("مرحبا").text === "string", "والناتج نصٌّ دائمًا");
}

console.log(`\n═══ ${P} نجحت · ${C} فشلت ═══\n`);
process.exit(C ? 1 : 0);
