// تنظيف: نتأكد أن كل سؤال صالح (سؤال + 4 خيارات + صعوبة)
function validate() {
  const problems = [];
  let total = 0;
  for (const [cat, list] of Object.entries(BANK)) {
    list.forEach((row, i) => {
      const opts = row.slice(1, 5);
      const d = row[5];
      if (typeof row[0] !== "string" || !row[0].trim()) problems.push(`${cat}[${i}] سؤال فارغ`);
      if (opts.length !== 4 || opts.some(o => typeof o !== "string" || !o.trim()))
        problems.push(`${cat}[${i}] خيارات ناقصة: ${row[0]}`);
      if (new Set(opts).size !== 4) problems.push(`${cat}[${i}] خيارات مكررة: ${row[0]}`);
      if (![1, 2, 3].includes(d)) problems.push(`${cat}[${i}] صعوبة غير صالحة: ${row[0]}`);
      total++;
    });
  }
  return { total, problems };
}

// الأسئلة المضافة من لوحة الإدارة (تُحمَّل من قاعدة البيانات)
// الأسئلة المولّدة آلياً من جداول الحقائق (qgen.js) — تُدمج مع البنك اليدوي
let GEN = {};
try { GEN = require("./qgen").generate(); } catch (e) { console.error("qgen:", e.message); }

let EXTRA = {};           // { فئة: [ [س, صح, خ, خ, خ, صعوبة, صورة؟], ... ] }
let REMOVED = new Set();  // نصوص أسئلة محذوفة
let OVER = {};            // تعديلات على أسئلة أساسية: { نص السؤال الأصلي: الصف الجديد }

function setExtra(obj) { EXTRA = obj || {}; }
function setRemoved(arr) { REMOVED = new Set(arr || []); }
function setOverrides(obj) { OVER = obj || {}; }

function categories() {
  return [...new Set([...Object.keys(BANK), ...Object.keys(GEN), ...Object.keys(EXTRA)])];
}

function poolOf(cat) {
  const base = BANK[cat] || [];
  const gen = GEN[cat] || [];
  const extra = EXTRA[cat] || [];
  const seen = new Set();
  return [...base, ...gen, ...extra]
    .filter(r => {
      if (REMOVED.has(r[0]) || seen.has(r[0])) return false;
      seen.add(r[0]); return true;
    })
    .map(r => OVER[r[0]] || r);   // التعديلات اليدوية تحلّ محل الأصل
}

function countAll() {
  return categories().reduce((n, c) => n + poolOf(c).length, 0);
}

function shuffle(a) {
  const x = a.slice();
  for (let i = x.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [x[i], x[j]] = [x[j], x[i]];
  }
  return x;
}

/**
 * سحب سؤال من فئة.
 * @param cat اسم الفئة
 * @param used Set لنصوص الأسئلة المستعملة (لمنع التكرار)
 * @param diff الصعوبة المطلوبة (1-3) أو 0 لأي صعوبة
 * @returns { id, text, options:[4], correct:index, cat, diff } أو null
 */
// صيغة السؤال المصوّر: العنصر السابع (r[6]) مسار صورة داخل /qimg/
function hasImage(r) { return typeof r[6] === "string" && r[6].length > 0; }

function draw(cat, used, diff = 0, allowImages = true) {
  let pool = poolOf(cat).filter(r => !used || !used.has(r[0]));
  if (!allowImages) pool = pool.filter(r => !hasImage(r));
  if (diff) {
    const byDiff = pool.filter(r => r[5] === diff);
    if (byDiff.length >= 3) pool = byDiff;
  }
  if (!pool.length) {
    // الفئة استُنفدت — نسمح بالتكرار بدل تعطيل اللعبة
    pool = poolOf(cat);
    if (!allowImages) pool = pool.filter(r => !hasImage(r));
    if (!pool.length) return null;
  }
  const row = pool[Math.floor(Math.random() * pool.length)];
  const correctText = row[1];
  const options = shuffle(row.slice(1, 5));
  return {
    id: row[0],
    text: row[0],
    options,
    correct: options.indexOf(correctText),
    cat,
    diff: row[5],
    img: hasImage(row) ? row[6] : null
  };
}

// اختيار مجموعة فئات للتصويت
function pickCategories(n = 4, exclude = []) {
  const avail = categories().filter(c => !exclude.includes(c) && poolOf(c).length > 0);
  return shuffle(avail).slice(0, Math.min(n, avail.length));
}

