// جولة ربط: يعيد { title, left[4], right[4], answer[4] }
// answer[i] = فهرس العنصر الصحيح في right للعنصر left[i]
function drawLink(used) {
  let pool = LINKS.filter(l => !used || !used.has(l.t + "|" + l.p[0][0]));
  if (!pool.length) pool = LINKS;
  const set = pool[Math.floor(Math.random() * pool.length)];
  return {
    id: set.t + "|" + set.p[0][0],
    title: set.t,
    pairs: set.p.map(x => [x[0], x[1]])   // [يمين، يسار] — ١٥ زوجًا
  };
}

// جولة تصنيف: يعيد { a, b, items[8], answer[8] }
function drawSort(used) {
  let pool = SORTS.filter(s => !used || !used.has(s.a + "|" + s.b));
  if (!pool.length) pool = SORTS;
  const set = pool[Math.floor(Math.random() * pool.length)];
  const mixed = shuffle(set.items);
  return {
    id: set.a + "|" + set.b,
    a: set.a, b: set.b,
    items: mixed.map(x => x[0]),
    answer: mixed.map(x => x[1])
  };
}

function validateChallenges() {
  const problems = [];
  LINKS.forEach((l, i) => {
    if (l.p.length !== 15) problems.push(`ربط[${i}] ${l.t}: عدد الأزواج ${l.p.length}`);
    if (new Set(l.p.map(x => x[1])).size !== 15) problems.push(`ربط[${i}] ${l.t}: طرف أيسر مكرر`);
    if (new Set(l.p.map(x => x[0])).size !== 15) problems.push(`ربط[${i}] ${l.t}: طرف أيمن مكرر`);
  });
  SORTS.forEach((s, i) => {
    const n = s.items.length;
    if (n < 15) problems.push(`تصنيف[${i}] ${s.a}: عدد العناصر ${n}`);
    // التوازن لا يعني التساوي التامّ: العدد فردي، فيكفي ألّا يزيد الفارق عن واحد
    const zeros = s.items.filter(x => x[1] === 0).length;
    if (Math.abs(zeros - (n - zeros)) > 1)
      problems.push(`تصنيف[${i}] ${s.a}/${s.b}: التوزيع ${zeros}/${n - zeros} غير متوازن`);
    if (s.items.some(x => ![0, 1].includes(x[1]))) problems.push(`تصنيف[${i}] ${s.a}: قيمة صندوق غير صالحة`);
    if (new Set(s.items.map(x => x[0])).size !== n) problems.push(`تصنيف[${i}] ${s.a}: عنصر مكرر`);
  });
  return { links: LINKS.length, sorts: SORTS.length, problems };
}

