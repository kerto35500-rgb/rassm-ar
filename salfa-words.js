const PACK_NAMES = Object.keys(PACKS);

function poolFrom(enabled) {
  const names = (Array.isArray(enabled) && enabled.length)
    ? enabled.filter(n => PACKS[n])
    : PACK_NAMES;
  const use = names.length ? names : PACK_NAMES;
  const out = [];
  use.forEach(n => PACKS[n].forEach(w => out.push({ cat: n, word: w })));
  return out;
}

function stats() {
  return { packs: PACK_NAMES.length, words: PACK_NAMES.reduce((a, n) => a + PACKS[n].length, 0) };
}

